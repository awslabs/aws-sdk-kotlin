package aws.sdk.kotlin.hll.dynamodbmapper

import aws.sdk.kotlin.hll.dynamodbmapper.items.AutoGeneratedConverter
import aws.sdk.kotlin.hll.dynamodbmapper.items.ItemConverter
import aws.sdk.kotlin.hll.dynamodbmapper.values.ValueConverter
import kotlin.reflect.KClass

/**
 * Specifies the attribute name for a property in a [DynamoDbItem]-annotated class/interface. If this annotation is not
 * included then the attribute name matches the property name.
 */
@Target(AnnotationTarget.PROPERTY)
public annotation class DynamoDbAttribute(val name: String)

/**
 * Specifies the type of [ValueConverter] to be used when processing this attribute.
 */
@Target(AnnotationTarget.PROPERTY)
public annotation class DynamoDbAttributeConverter(val converter: KClass<out ValueConverter<*>>)

/**
 * Specifies that this class/interface can be mapped to/from a set of DynamoDB attributes (an item). An
 * [ItemConverter] will be generated for the annotated type, allowing it to be used as a nested attribute within
 * another [DynamoDbMappable] or [DynamoDbItem] type. Unlike [DynamoDbItem], a type annotated only with
 * [DynamoDbMappable] does not describe a table item and therefore does not require (or permit) primary key, TTL, or
 * counter annotations.
 *
 * [DynamoDbItem] is itself a [DynamoDbMappable] type, so any [DynamoDbItem] may also be nested within another mappable
 * type without additional annotations.
 * @param converter The item converter to be used for converting this class/interface. If not set, one will be
 * automatically generated.
 */
@Target(AnnotationTarget.CLASS, AnnotationTarget.ANNOTATION_CLASS)
@Retention(AnnotationRetention.BINARY)
public annotation class DynamoDbMappable(val converter: KClass<out ItemConverter<*>> = AutoGeneratedConverter::class)

/**
 * Specifies that this class/interface describes an item type in a table. All public properties of this type will be mapped to
 * attributes unless they are explicitly ignored.
 *
 * This annotation is a specialization of [DynamoDbMappable]: in addition to generating an [ItemConverter], it enforces
 * primary key requirements and generates a table schema. Its properties may reference other [DynamoDbMappable] or
 * [DynamoDbItem] types as nested attributes.
 * @param converter The item converter to be used for converting this class/interface. If not set, one will be automatically generated.
 */
@Target(AnnotationTarget.CLASS)
@DynamoDbMappable
public annotation class DynamoDbItem(val converter: KClass<out ItemConverter<*>> = AutoGeneratedConverter::class)

/**
 * Specifies that this class/interface is the base of a heterogeneous family of mappable types, distinguished by a
 * string type name stored in [typeAttribute]. A `HeterogeneousItemConverter` will be generated for the annotated type
 * from every [DynamoDbSubtype] registered in this family.
 *
 * When applied to an `object`, the object serves only as a name for an ad-hoc family whose common type is [Any]. Such
 * a family's subtypes must name the object explicitly via [DynamoDbSubtype.parent], and properties holding its values
 * must be annotated with [DynamoDbHeterogeneousAttribute].
 *
 * Combine with [DynamoDbItem] to make the family a table item (generating a schema and table accessor). Without
 * [DynamoDbItem], the family is usable only as a nested attribute.
 * @param typeAttribute The name of the attribute which stores the type name of each item
 * @param baseTypeName If non-empty, registers instances of the base type itself under this type name. Valid only on an
 * open concrete class. If empty (the default), the base type itself is not registered.
 * @param baseMatch How objects are matched to the base type's own registration. Ignored when [baseTypeName] is empty.
 */
@Target(AnnotationTarget.CLASS)
@DynamoDbMappable
public annotation class DynamoDbHeterogeneousType(
    val typeAttribute: String,
    val baseTypeName: String = "",
    val baseMatch: DynamoDbSubtypeMatch = DynamoDbSubtypeMatch.INSTANCE_OF,
)

/**
 * Specifies that this class/interface is a member of a [DynamoDbHeterogeneousType] family, stored under [typeName].
 * This annotation implies [DynamoDbMappable].
 * @param typeName The value stored in the family's type attribute for objects matching this type. Must be non-blank
 * and unique within the family.
 * @param match How objects are matched to this type
 * @param parent The family this type belongs to. If not set, the family is inferred from this type's supertypes. Must
 * be set when the family's base is an ad-hoc `object`.
 * @param converter The item converter to be used for this type. If not set, one will be automatically generated.
 */
@Target(AnnotationTarget.CLASS)
@DynamoDbMappable
public annotation class DynamoDbSubtype(
    val typeName: String,
    val match: DynamoDbSubtypeMatch = DynamoDbSubtypeMatch.INSTANCE_OF,
    val parent: KClass<*> = Any::class,
    val converter: KClass<out ItemConverter<*>> = AutoGeneratedConverter::class,
)

/**
 * Determines how objects are matched to a [DynamoDbSubtype]. Mirrors the `HeterogeneousItemConverter.Builder` methods.
 */
public enum class DynamoDbSubtypeMatch {
    /**
     * Matches objects whose class is exactly the annotated type. Corresponds to `Builder.exactType`.
     */
    EXACT_TYPE,

    /**
     * Matches objects which are instances of the annotated type or any of its subtypes. Corresponds to
     * `Builder.instanceOf`.
     */
    INSTANCE_OF,
}

/**
 * Specifies that this property's value is a member of the [DynamoDbHeterogeneousType] family [family], converted with
 * that family's generated value converter. Required for ad-hoc families, whose value type is [Any] and so can't be
 * inferred from the property's type.
 *
 * Applies to the property's family-typed value, including inside collections (e.g., `List<Any>`, `Map<String, Any?>`).
 * @param family The family's base, which must be annotated with [DynamoDbHeterogeneousType]
 */
@Target(AnnotationTarget.PROPERTY)
public annotation class DynamoDbHeterogeneousAttribute(val family: KClass<*>)

/**
 * Specifies that this property is the primary key for the item. Every top-level [DynamoDbItem] to be used in a table
 * must have exactly one partition key.
 */
@Target(AnnotationTarget.PROPERTY)
public annotation class DynamoDbPartitionKey

/**
 * Specifies that this property is the sort key for the item. Every top-level [DynamoDbItem] to be used in a table may
 * have at most one sort key.
 */
@Target(AnnotationTarget.PROPERTY)
public annotation class DynamoDbSortKey

/**
 * Specifies that this property should be ignored during mapping.
 */
@Target(AnnotationTarget.PROPERTY)
public annotation class DynamoDbIgnore

/**
 * Specifies that this property is used to track the item's time-to-live (TTL).
 * https://docs.aws.amazon.com/amazondynamodb/latest/developerguide/TTL.html
 * @param lifetime The lifetime of this item, in seconds
 */
@Target(AnnotationTarget.PROPERTY)
public annotation class DynamoDbTtlSeconds(val lifetime: Long)

/**
 * Specifies that this property should be used as a counter field, incrementing each time an item is persisted to DynamoDB.
 */
@Target(AnnotationTarget.PROPERTY)
public annotation class DynamoDbCounter
