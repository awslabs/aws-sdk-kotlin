/**
 * Renders the classes and objects required to make a class usable with the DynamoDbMapper such as schemas, builders, and converters.
 * @param classDeclaration the [KSClassDeclaration] of the class
 * @param ctx the [RenderContext] of the renderer
 */
@OptIn(KspExperimental::class)
internal class SchemaRenderer(
    private val classDeclaration: KSClassDeclaration,
    private val ctx: RenderContext,
) : RendererBase(ctx, "${classDeclaration.qualifiedName!!.getShortName()}Schema") {
    private val className = classDeclaration.qualifiedName!!.getShortName()
    private val classStructure = Structure.from(classDeclaration)
    private val classType = Type.from(classDeclaration)

    private val builderName = "${className}Builder"
    private val converterName = "${className}Converter"
    private val schemaName = "${className}Schema"

    private val shouldRenderItemConverter: Boolean
    private val itemConverter: Type

    /**
     * Whether the annotated type is a table item ([DynamoDbItem]) as opposed to a nested-only mappable type
     * ([DynamoDbMappable]). Table items enforce primary key requirements and generate a schema + table accessor;
     * nested types generate only converters.
     */
    private val isTableItem = classDeclaration.isAnnotationPresent(DynamoDbItem::class)

    private val properties = classDeclaration.getMappedProperties()

    private val partitionKeyProps = properties.filter { it.isPk }
    private val sortKeyProps = properties.filter { it.isSk }

    private val partitionKeyTypeRefs = partitionKeyProps.map { it.typeRef }
    private val sortKeyTypeRefs = sortKeyProps.map { it.typeRef }

    /**
     * Skip rendering a class builder if:
     *   - the user has configured GenerateBuilders to WHEN_REQUIRED (default value) AND
     *   - the class has all mutable members AND
     *   - the class has a zero-arg constructor
     */
    private val shouldRenderBuilder: Boolean = run {
        val alwaysGenerateBuilders = ctx.attributes[AnnotationsProcessorOptions.GenerateBuilderClassesAttribute] == GenerateBuilderClasses.ALWAYS
        val hasAllMutableMembers = properties.all { it.isMutable }
        val hasZeroArgConstructor = classDeclaration.getConstructors().any { constructor -> constructor.parameters.all { it.hasDefault } }

        !(!alwaysGenerateBuilders && hasAllMutableMembers && hasZeroArgConstructor)
    }

    init {
        // @DynamoDbMappable targets ANNOTATION_CLASS so it can meta-annotate @DynamoDbItem, which means the Kotlin
        // compiler alone won't stop a user from incorrectly applying it to their own annotation class. Fail fast with a
        // located diagnostic in that case.
        if (classDeclaration.classKind == ClassKind.ANNOTATION_CLASS) {
            val msg = "@DynamoDbMappable cannot be applied to annotation classes " +
                "(${classDeclaration.qualifiedName?.asString()}); it is only valid on regular or data classes."
            ctx.logger.error(msg, classDeclaration)
            error(msg)
        }

        // Read the user-specified converter (if any) from whichever marker annotation applies to this type.
        val markerQualifiedName = if (isTableItem) {
            DynamoDbItem::class.qualifiedName
        } else {
            DynamoDbMappable::class.qualifiedName
        }

        val specifiedItemConverter = classDeclaration
            .annotations
            .firstOrNull { it.annotationType.resolve().declaration.qualifiedName?.asString() == markerQualifiedName }
            ?.arguments
            ?.singleOrNull()
            ?.value
            ?.let { it as KSType }
            ?.takeUnless { it.declaration.qualifiedName!!.asString() == AutoGeneratedConverter::class.qualifiedName }

        shouldRenderItemConverter = specifiedItemConverter == null

        itemConverter = specifiedItemConverter?.let(Type::from) ?: TypeRef(ctx.pkg, converterName)
    }

    override fun generate() {
        if (isTableItem) {
            validateTableItemKeys()
        } else {
            validateNestedItem()
        }

        if (shouldRenderBuilder) {
            renderBuilder()
        }

        if (shouldRenderItemConverter) {
            renderItemConverter()
        }

        if (ctx.attributes[SchemaAttributes.ShouldRenderValueConverterAttribute]) {
            renderValueConverter()
        }

        if (isTableItem) {
            renderSchema()

            if (ctx.attributes[AnnotationsProcessorOptions.GenerateGetTableMethodAttribute]) {
                renderGetTable()
            }
        }
    }

    /**
     * Validates primary key requirements for a table item ([DynamoDbItem]). Mirrors the historical fail-fast behavior:
     * exactly 1-4 partition key properties and 0-4 sort key properties.
     */
    private fun validateTableItemKeys() {
        require(partitionKeyProps.size in 1..4) {
            "Expected between 1 and 4 properties annotated with @DynamoDbPartitionKey, found ${partitionKeyProps.size}"
        }
        require(sortKeyProps.size in 0..4) {
            "Expected between 0 and 4 properties annotated with @DynamoDbSortKey, found ${sortKeyProps.size}"
        }
    }

    /**
     * Validates a nested-only mappable type ([DynamoDbMappable] without [DynamoDbItem]). Key, TTL, and counter
     * annotations are meaningful only on table items, so their presence on a nested type is a compile-time error.
     */
    private fun validateNestedItem() {
        properties.forEach { prop ->
            val invalidAnnotations = buildList {
                if (prop.isPk) add("@DynamoDbPartitionKey")
                if (prop.isSk) add("@DynamoDbSortKey")
                if (prop.isAnnotationPresent(DynamoDbTtlSeconds::class)) add("@DynamoDbTtlSeconds")
                if (prop.isAnnotationPresent(DynamoDbCounter::class)) add("@DynamoDbCounter")
            }

            if (invalidAnnotations.isNotEmpty()) {
                ctx.logger.error(
                    "Property '${prop.name}' on nested type '$className' is annotated with " +
                        "${invalidAnnotations.joinToString()}. These annotations are only valid on a @DynamoDbItem " +
                        "table item, not on a nested @DynamoDbMappable type.",
                    prop,
                )
            }
        }
    }

    private fun renderBuilder() {
        val builderCtx = ctx.copy(
            attributes = ctx.attributes + (ModelAttributes.GeneratedApi to true),
        )
        val members = properties.map(Member::from).toSet()
        BuilderRenderer(builderCtx, this, classStructure, classType, members).render()
    }

    private fun renderItemConverter() {
        generatedAnnotation()
        withBlock(
            "#Lobject #L : #T by #T(",
            ")",
            ctx.attributes.visibility,
            converterName,
            MapperTypes.Items.itemConverter(classType),
            MapperTypes.Items.SimpleItemConverter,
        ) {
            if (shouldRenderBuilder) {
                write("builderFactory = ::#L,", builderName)
                write("build = #L::build,", builderName)
            } else {
                write("builderFactory = { $className() },")
                write("build = { this },")
            }

            withBlock("descriptors = arrayOf(", "),") {
                properties.forEach {
                    renderAttributeDescriptor(it)
                }
            }
        }
        blankLine()
    }

    /**
     * Render a [ValueConverter] for the current class by wrapping the generated/user-provided [ItemConverter]
     * with our [ItemValueConverter].
     */
    private fun renderValueConverter() {
        generatedAnnotation()
        write(
            "#Lval #L: #T = #T(#T, #T)",
            ctx.attributes.visibility,
            "${className}ValueConverter",
            MapperTypes.Values.valueConverter(classType),
            HllTypes.MappingCore.Converters.ConverterChain,
            itemConverter,
            MapperTypes.Values.ItemValueConverter,
        )
        blankLine()
    }

    private fun renderAttributeDescriptor(prop: KSPropertyDeclaration) {
        ctx.logger.info("Rendering an attribute descriptor for ${prop.simpleName.asString()}")
        withBlock("#T(", "),", MapperTypes.Items.AttributeDescriptor) {
            write("#S,", prop.ddbName) // key
            write("#L,", "$className::${prop.name}") // getter

            // setter
            if (shouldRenderBuilder) {
                write("#L,", "$builderName::${prop.name}::set")
            } else {
                write("#L,", "$className::${prop.name}::set")
            }

            // converter
            // KSP requires extra work to get a class argument out of an annotation, can't just use getAnnotationsByType
            // https://slack-chats.kotlinlang.org/t/8480301/hello-again-how-do-you-get-a-kclass-out-from-an-annotation-a
            val attributeValueConverterKsType = prop
                .annotations
                .singleOrNull { it.annotationType.resolve().declaration.qualifiedName?.asString() == DynamoDbAttributeConverter::class.qualifiedName }
                ?.arguments
                ?.single()
                ?.value
                ?.let { it as KSType }

            val attributeValueConverter = attributeValueConverterKsType?.let { Type.from(it) }
            val needsCtorInvoke = attributeValueConverterKsType?.declaration?.isObject != true

            attributeValueConverter?.let {
                writeInline("#T", it)

                if (needsCtorInvoke) {
                    writeInline("()")
                }
            } ?: run {
                renderValueConverter(prop.type.resolve())
            }
            write(",")
        }
    }

    /**
     * Renders a ValueConverter for the [ksType].
     *
     * Note: The ValueConverter(s) will be rendered without a newline in order to support deep recursion.
     * Callers are responsible for adding a newline after the top-level invocation of this function.
     */
    private fun renderValueConverter(ksType: KSType) {
        val type = Type.from(ksType)

        when {
            type.nullable -> {
                writeInline("#T(", MapperTypes.Values.NullableValueConverter)
                renderValueConverter(ksType.makeNotNullable())
                writeInline(")")
            }

            ksType.isEnum -> writeInline("#T()", MapperTypes.Values.Scalars.enumValueConverter(type))

            // Nested @DynamoDbMappable / @DynamoDbItem type: reference its generated value converter.
            ksType.isUserClass -> {
                val decl = ksType.declaration

                // Multi-module nesting is out of scope for now. Declarations originating from binary dependencies have
                // no containing source file; fail fast rather than emitting a reference that won't resolve.
                if (decl.containingFile == null) {
                    ctx.logger.error(
                        "Nested type '${decl.qualifiedName?.asString()}' is defined in another module. Nesting " +
                            "@DynamoDbMappable types across modules is not yet supported; the nested type must be " +
                            "declared in the same module as the type that references it.",
                        decl,
                    )
                    return
                }

                writeInline("#T", TypeRef(nestedConverterPackage(decl), "${decl.simpleName.asString()}ValueConverter"))
            }

            type.isGenericFor(Types.Kotlin.Collections.List) -> {
                val listElementType = ksType.singleArgument()
                writeInline("#T(", MapperTypes.Values.Collections.ListValueConverter)
                renderValueConverter(listElementType)
                writeInline(")")
            }

            type.isGenericFor(Types.Kotlin.Collections.Map) -> {
                check(ksType.arguments.size == 2) { "Expected map type ${ksType.declaration.qualifiedName?.asString()} to have 2 arguments, got ${ksType.arguments.size}" }

                val (keyType, valueType) = ksType.arguments.map {
                    checkNotNull(it.type?.resolve()) { "Failed to resolved argument type for $it" }
                }

                if (keyType.isEnum) {
                    writeInline("#T(#T(), ", MapperTypes.Values.Collections.MapValueConverter, MapperTypes.Values.Scalars.enumToStringConverter(Type.from(keyType)))
                } else {
                    writeInline("#T(#T, ", MapperTypes.Values.Collections.MapValueConverter, keyType.mapKeyConverter)
                }
                renderValueConverter(valueType)
                writeInline(")")
            }

            type.isGenericFor(Types.Kotlin.Collections.Set) -> {
                val setElementType = ksType.singleArgument()
                if (setElementType.isEnum) {
                    writeInline("#T()", MapperTypes.Values.Collections.enumSetValueConverter(Type.from(setElementType)))
                } else {
                    writeInline("#T", setElementType.setValueConverter)
                }
            }

            else -> writeInline(
                "#T",
                when (type) {
                    Types.Smithy.Instant -> MapperTypes.Values.SmithyTypes.InstantValueConverter
                    Types.Smithy.Url -> MapperTypes.Values.SmithyTypes.UrlValueConverter
                    Types.Smithy.Document -> MapperTypes.Values.SmithyTypes.DocumentValueConverter
                    Types.Smithy.BigDecimal -> MapperTypes.Values.SmithyTypes.BigDecimalValueConverter
                    Types.Smithy.BigInteger -> MapperTypes.Values.SmithyTypes.BigIntegerValueConverter

                    Types.Java.BigDecimal -> MapperTypes.Values.JavaMath.BigDecimalValueConverter
                    Types.Java.BigInteger -> MapperTypes.Values.JavaMath.BigIntegerValueConverter

                    Types.Kotlin.Boolean -> MapperTypes.Values.Scalars.BooleanValueConverter
                    Types.Kotlin.String -> MapperTypes.Values.Scalars.StringValueConverter
                    Types.Kotlin.CharArray -> MapperTypes.Values.Scalars.CharArrayValueConverter
                    Types.Kotlin.Char -> MapperTypes.Values.Scalars.CharValueConverter
                    Types.Kotlin.Byte -> MapperTypes.Values.Scalars.ByteValueConverter
                    Types.Kotlin.ByteArray -> MapperTypes.Values.Scalars.ByteArrayValueConverter
                    Types.Kotlin.Short -> MapperTypes.Values.Scalars.ShortValueConverter
                    Types.Kotlin.Int -> MapperTypes.Values.Scalars.IntValueConverter
                    Types.Kotlin.Long -> MapperTypes.Values.Scalars.LongValueConverter
                    Types.Kotlin.Double -> MapperTypes.Values.Scalars.DoubleValueConverter
                    Types.Kotlin.Float -> MapperTypes.Values.Scalars.FloatValueConverter
                    Types.Kotlin.UByte -> MapperTypes.Values.Scalars.UByteValueConverter
                    Types.Kotlin.UInt -> MapperTypes.Values.Scalars.UIntValueConverter
                    Types.Kotlin.UShort -> MapperTypes.Values.Scalars.UShortValueConverter
                    Types.Kotlin.ULong -> MapperTypes.Values.Scalars.ULongValueConverter
                    else -> error(unsupportedAttributeTypeMessage(ksType, type))
                },
            )
        }
    }

    /**
     * Computes the package into which the generated value converter for a nested [decl] is emitted, matching the
     * destination-package logic used when the nested type itself is processed. This allows a nested type to live in a
     * different package than the referencing type (within the same module).
     */
    private fun nestedConverterPackage(decl: KSDeclaration): String = when (
        val dstPkg = ctx.attributes[AnnotationsProcessorOptions.DestinationPackageAttribute]
    ) {
        is DestinationPackage.Relative -> "${decl.packageName.asString()}.${dstPkg.pkg}"
        is DestinationPackage.Absolute -> dstPkg.pkg
    }

    /**
     * Builds an error message for an unsupported attribute type. When the type is a user-defined class, hints that it
     * may need a [DynamoDbMappable] annotation to be usable as a nested attribute.
     */
    private fun unsupportedAttributeTypeMessage(ksType: KSType, type: Type): String {
        val decl = ksType.declaration
        val isUserDefinedClass = (decl as? KSClassDeclaration)?.classKind == ClassKind.CLASS
        return if (isUserDefinedClass) {
            "Unsupported attribute type $type. If '${decl.qualifiedName?.asString()}' should be stored as a nested " +
                "item, annotate it with @DynamoDbMappable (or @DynamoDbItem)."
        } else {
            "Unsupported attribute type $type"
        }
    }

    private val KSType.mapKeyConverter: Type
        get() = when (val type = Type.from(this)) {
            // String
            Types.Kotlin.ByteArray -> MapperTypes.Values.Scalars.CharArrayToStringConverter
