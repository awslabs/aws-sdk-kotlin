/*
 * Discovery and structural validation of heterogeneous families (@DynamoDbHeterogeneousType + @DynamoDbSubtype). This
 * runs once per batch, before per-class extraction, because membership, completeness and naming are cross-class facts.
 */

private val heterogeneousTypeName = DynamoDbHeterogeneousType::class.qualifiedName!!
private val subtypeName = DynamoDbSubtype::class.qualifiedName!!
private val itemName = DynamoDbItem::class.qualifiedName!!
private const val ANY_NAME = "kotlin.Any"

/**
 * A heterogeneous family: a [base] annotated with [DynamoDbHeterogeneousType] and the [members] registered in it
 */
internal class Family(
    val base: KSClassDeclaration,
    val typeAttribute: String,
    /** The type name under which the base registers itself, or `null` if it doesn't */
    val baseTypeName: String?,
    val baseExact: Boolean,
) {
    val qualifiedName: String = base.qualifiedName!!.asString()
    val isTable: Boolean = base.annotationNamed(itemName) != null

    /** Whether this is an ad-hoc family named by an `object`, whose value type is [Any] */
    val isAdHoc: Boolean = base.classKind == ClassKind.OBJECT
    val members = mutableListOf<FamilyMember>()

    /** The membership of this family's base in an outer family, if it is itself a [DynamoDbSubtype] */
    var outer: FamilyMember? = null
}

/**
 * A [DynamoDbSubtype] registered in [family]
 * @param customConverter The user-provided item converter from [DynamoDbSubtype.converter], if any
 */
internal class FamilyMember(
    val decl: KSClassDeclaration,
    val typeName: String,
    val exact: Boolean,
    val family: Family,
    val customConverter: KSType?,
) {
    val qualifiedName: String = decl.qualifiedName!!.asString()
}

/**
 * The families found in a batch, indexed by qualified name
 */
internal class FamilyIndex(
    val families: Map<String, Family>,
    val memberships: Map<String, FamilyMember>,
) {
    fun familyOf(decl: KSDeclaration): Family? = families[decl.qualifiedName?.asString()]
    fun membershipOf(decl: KSDeclaration): FamilyMember? = memberships[decl.qualifiedName?.asString()]

    /**
     * Whether [family] is (transitively) part of a table family, which permits key, TTL and counter annotations on its
     * members
     */
    fun inTableContext(family: Family): Boolean = family.isTable || family.outer?.let { inTableContext(it.family) } == true

    /**
     * The type attributes written by [family] and every family it is nested in, innermost first
     */
    fun typeAttributeChain(family: Family): List<String> = listOf(family.typeAttribute) +
        family.outer?.let { typeAttributeChain(it.family) }.orEmpty()

    companion object {
        val Empty = FamilyIndex(emptyMap(), emptyMap())
    }
}

/**
 * Finds every family among [classes], resolves each subtype's family, and validates the families' structure
 */
internal fun resolveFamilies(classes: List<KSClassDeclaration>, diagnostics: DiagnosticCollector): FamilyIndex {
    val families = classes.mapNotNull { decl ->
        val annotation = decl.annotationNamed(heterogeneousTypeName) ?: return@mapNotNull null
        val baseTypeName = annotation.argument("baseTypeName") as? String ?: ""
        Family(
            base = decl,
            typeAttribute = annotation.argument("typeAttribute") as? String ?: "",
            baseTypeName = baseTypeName.takeUnless { it.isEmpty() },
            baseExact = annotation.enumArgument("baseMatch", DynamoDbSubtypeMatch.EXACT_TYPE) == DynamoDbSubtypeMatch.EXACT_TYPE,
        )
    }.associateBy { it.qualifiedName }

    val memberships = mutableMapOf<String, FamilyMember>()
    classes.forEach { decl ->
        val annotation = decl.annotationNamed(subtypeName) ?: return@forEach
        val family = resolveFamily(decl, annotation, families, diagnostics) ?: return@forEach

        val member = FamilyMember(
            decl = decl,
            typeName = annotation.argument("typeName") as? String ?: "",
            exact = annotation.enumArgument("match", DynamoDbSubtypeMatch.EXACT_TYPE) == DynamoDbSubtypeMatch.EXACT_TYPE,
            family = family,
            customConverter = (annotation.argument("converter") as? KSType)
                ?.takeUnless { it.declaration.qualifiedName?.asString() == AutoGeneratedConverter::class.qualifiedName },
        )
        family.members += member
        memberships[member.qualifiedName] = member
        families[member.qualifiedName]?.outer = member
    }

    val index = FamilyIndex(families, memberships)
    families.values.forEach { validateFamily(it, index, diagnostics) }
    return index
}

private fun resolveFamily(
    decl: KSClassDeclaration,
    annotation: KSAnnotation,
    families: Map<String, Family>,
    diagnostics: DiagnosticCollector,
): Family? {
    val name = decl.qualifiedName!!.asString()
    val parent = (annotation.argument("parent") as? KSType)?.declaration
        ?.takeUnless { it.qualifiedName?.asString() == ANY_NAME }

    if (parent != null) {
        val parentName = parent.qualifiedName!!.asString()
        val family = families[parentName]
        when {
            family == null && parent.containingFile == null -> diagnostics.error(
                "Family '$parentName' of subtype '$name' is defined in another module. A @DynamoDbSubtype must be " +
                    "declared in the same module as its @DynamoDbHeterogeneousType family.",
                decl.asSymbolRef(),
            )
            family == null -> diagnostics.error(
                "Parent '$parentName' of subtype '$name' is not annotated with @DynamoDbHeterogeneousType",
                decl.asSymbolRef(),
            )
            !family.isAdHoc && !decl.isSubclassOf(parentName) -> diagnostics.error(
                "Subtype '$name' is not a subtype of its parent family '$parentName'",
                decl.asSymbolRef(),
            )
            else -> return family
        }
        return null
    }

    // Walk supertypes breadth-first, stopping each path at its first family and skipping unannotated intermediates
    val found = linkedSetOf<String>()
    val visited = mutableSetOf<String>()
    val queue = ArrayDeque(decl.superClassDeclarations())
    while (queue.isNotEmpty()) {
        val superDecl = queue.removeFirst()
        val superName = superDecl.qualifiedName?.asString() ?: continue
        if (superName == ANY_NAME || !visited.add(superName)) continue

        if (superDecl.annotationNamed(heterogeneousTypeName) != null) {
            found += superName
        } else {
            queue.addAll(superDecl.superClassDeclarations())
        }
    }

    return when (found.size) {
        0 -> {
            diagnostics.error(
                "No @DynamoDbHeterogeneousType family found for subtype '$name'. Annotate a supertype with " +
                    "@DynamoDbHeterogeneousType, or set `parent` to name an ad-hoc family.",
                decl.asSymbolRef(),
            )
            null
        }
        1 -> {
            val familyName = found.single()
            families[familyName] ?: run {
                diagnostics.error(
                    "Family '$familyName' of subtype '$name' is defined in another module. A @DynamoDbSubtype must " +
                        "be declared in the same module as its @DynamoDbHeterogeneousType family.",
                    decl.asSymbolRef(),
                )
                null
            }
        }
        else -> {
            diagnostics.error(
                "Subtype '$name' belongs to multiple families (${found.joinToString { "'$it'" }}). A type may " +
                    "belong to only one family; set `parent` to choose one.",
                decl.asSymbolRef(),
            )
            null
        }
    }
}

private fun validateFamily(family: Family, index: FamilyIndex, diagnostics: DiagnosticCollector) {
    val base = family.base
    val baseRef = base.asSymbolRef()
    val name = family.qualifiedName

    if (family.typeAttribute.isBlank()) {
        diagnostics.error("typeAttribute of family '$name' must not be blank", baseRef)
    }

    if (base.classKind in setOf(ClassKind.ENUM_CLASS, ClassKind.ENUM_ENTRY, ClassKind.ANNOTATION_CLASS) ||
        (base.classKind == ClassKind.CLASS && !base.isOpen)
    ) {
        diagnostics.error(
            "@DynamoDbHeterogeneousType cannot be applied to '$name' because it cannot have subtypes. Apply it to " +
                "a sealed, abstract or open type, an interface, or an `object` naming an ad-hoc family.",
            baseRef,
        )
    }

    if (family.members.isEmpty()) {
        diagnostics.error("Family '$name' must have at least one @DynamoDbSubtype", baseRef)
    }

    if (family.baseTypeName != null && (base.classKind != ClassKind.CLASS || base.isAbstract)) {
        diagnostics.error(
            "baseTypeName is set on family '$name', but its base cannot be instantiated. Only an open concrete " +
                "class may register itself.",
            baseRef,
        )
    }

    if (base.annotationNamed(itemName)?.converterArgument() != null) {
        diagnostics.error(
            "Family '$name' specifies a converter in @DynamoDbItem, which conflicts with the converter generated " +
                "for @DynamoDbHeterogeneousType",
            baseRef,
        )
    }

    family.outer?.let { outer ->
        if (outer.family.typeAttribute == family.typeAttribute) {
            diagnostics.error(
                "Family '$name' uses type attribute '${family.typeAttribute}', which collides with the type " +
                    "attribute of its outer family '${outer.family.qualifiedName}'",
                baseRef,
            )
        }
    }

    // Type names, including the base's own registration
    val seen = mutableMapOf<String, String>()
    val typeNames = family.members.map { it.typeName to it.decl } + listOfNotNull(family.baseTypeName?.let { it to base })
    typeNames.forEach { (typeName, decl) ->
        val declName = decl.qualifiedName!!.asString()
        if (typeName.isBlank()) {
            diagnostics.error("typeName of subtype '$declName' must not be blank", decl.asSymbolRef())
            return@forEach
        }
        seen.putIfAbsent(typeName, declName)?.let { existing ->
            diagnostics.error(
                "Type name '$typeName' of '$declName' is already registered in family '$name' by '$existing'",
                decl.asSymbolRef(),
            )
        }
    }

    family.members.forEach { validateMember(it, index, diagnostics) }

    if (family.baseTypeName != null) {
        validateTypeAttributeCollisions(base, index.typeAttributeChain(family), diagnostics)
    }

    if (Modifier.SEALED in base.modifiers) validateSealedCompleteness(family, diagnostics)
}

private fun validateMember(member: FamilyMember, index: FamilyIndex, diagnostics: DiagnosticCollector) {
    val decl = member.decl
    val ref = decl.asSymbolRef()
    val isFamily = index.familyOf(decl) != null

    if (member.exact && decl.isAbstract) {
        diagnostics.error(
            "Subtype '${member.qualifiedName}' uses EXACT_TYPE but is abstract or an interface, so it can never " +
                "match. Use INSTANCE_OF instead.",
            ref,
        )
    }

    if (!member.exact && decl.isAbstract && member.customConverter == null && !isFamily) {
        diagnostics.error(
            "Subtype '${member.qualifiedName}' uses INSTANCE_OF but is abstract or an interface, so its instances " +
                "can't be constructed on read. Supply a `converter`, or annotate it with @DynamoDbHeterogeneousType.",
            ref,
        )
    }

    if (member.customConverter != null) {
        val itemConverter = decl.annotationNamed(itemName)?.converterArgument()
        if (itemConverter != null) {
            diagnostics.error(
                "Subtype '${member.qualifiedName}' specifies a converter in both @DynamoDbItem and @DynamoDbSubtype",
                ref,
            )
        }
    }

    // A nested family's members are checked against the whole chain when their own family is validated
    if (!isFamily && member.customConverter == null) {
        validateTypeAttributeCollisions(decl, index.typeAttributeChain(member.family), diagnostics)
    }
}

private fun validateTypeAttributeCollisions(
    decl: KSClassDeclaration,
    typeAttributes: List<String>,
    diagnostics: DiagnosticCollector,
) {
    decl.getSourceProperties(inherit = true).forEach { prop ->
        if (prop.mapped.ddbName in typeAttributes) {
            diagnostics.error(
                "Property '${prop.mapped.name}' of '${decl.qualifiedName?.asString()}' maps to attribute " +
                    "'${prop.mapped.ddbName}', which collides with a type attribute of its family",
                prop.decl.asSymbolRef(),
            )
        }
    }
}

/**
 * Every concrete class descending from a sealed base, looking through unannotated intermediates, must be matched by
 * some registration; otherwise writing it fails at runtime.
 */
private fun validateSealedCompleteness(family: Family, diagnostics: DiagnosticCollector) {
    family.base.concreteSealedDescendants().forEach { descendant ->
        val covered = family.members.any { member ->
            if (member.exact) {
                member.qualifiedName == descendant.qualifiedName?.asString()
            } else {
                member.qualifiedName == descendant.qualifiedName?.asString() || descendant.isSubclassOf(member.qualifiedName)
            }
        }
        if (!covered) {
            diagnostics.error(
                "'${descendant.qualifiedName?.asString()}' is a concrete subtype of sealed family " +
                    "'${family.qualifiedName}' but is not matched by any @DynamoDbSubtype registration",
                descendant.asSymbolRef(),
            )
        }
    }
}

private fun KSClassDeclaration.concreteSealedDescendants(): Sequence<KSClassDeclaration> = getSealedSubclasses().flatMap { sub ->
    when {
        Modifier.SEALED in sub.modifiers -> sub.concreteSealedDescendants()
        sub.isAbstract -> emptySequence() // An abstract or interface subtype's own subtypes can't be enumerated
        else -> sequenceOf(sub)
    }
}

/**
 * Orders registrations so that one whose class is a subtype of another's comes first; otherwise the supertype's
 * `instanceOf` would shadow it. Ties are broken by [key] so output is deterministic.
 * @param ancestors The qualified names of each item's supertypes
 */
internal fun <T> orderRegistrations(items: List<T>, key: (T) -> String, ancestors: (T) -> Set<String>): List<T> {
    val remaining = items.sortedBy(key).toMutableList()
    val ordered = mutableListOf<T>()
    while (remaining.isNotEmpty()) {
        // Next is the first item that no remaining item descends from
        val next = remaining.firstOrNull { candidate -> remaining.none { it !== candidate && key(candidate) in ancestors(it) } }
            ?: remaining.first() // unreachable for a real hierarchy, which is acyclic
        remaining.remove(next)
        ordered += next
    }
    return ordered
}

internal fun KSClassDeclaration.ancestorNames(): Set<String> = getAllSuperTypes()
    .mapNotNull { it.declaration.qualifiedName?.asString() }
    .toSet()

private fun KSClassDeclaration.isSubclassOf(qualifiedName: String): Boolean = qualifiedName in ancestorNames()

private fun KSClassDeclaration.superClassDeclarations(): List<KSClassDeclaration> = superTypes
    .mapNotNull { it.resolve().declaration as? KSClassDeclaration }
    .toList()

internal val KSClassDeclaration.isAbstract: Boolean
    get() = classKind == ClassKind.INTERFACE || Modifier.ABSTRACT in modifiers || Modifier.SEALED in modifiers

private val KSClassDeclaration.isOpen: Boolean
    get() = isAbstract || Modifier.OPEN in modifiers

internal fun KSDeclaration.annotationNamed(qualifiedName: String): KSAnnotation? = annotations.firstOrNull { it.qualifiedName == qualifiedName }

/**
 * The user-specified item converter of a marker annotation, or `null` if it is unset
 */
internal fun KSAnnotation.converterArgument(): KSType? = (argument("converter") as? KSType)
    ?.takeUnless { it.declaration.qualifiedName?.asString() == AutoGeneratedConverter::class.qualifiedName }

/**
 * Reads an enum argument. KSP represents enum values as the enum entry's declaration or as its type depending on the
 * implementation, and may omit defaulted arguments entirely.
 */
private fun KSAnnotation.enumArgument(name: String, default: DynamoDbSubtypeMatch): DynamoDbSubtypeMatch {
    val entryName = when (val value = argument(name)) {
        is KSDeclaration -> value.simpleName.asString()
        is KSType -> value.declaration.simpleName.asString()
        null -> return default
        else -> value.toString().substringAfterLast('.')
    }
    return DynamoDbSubtypeMatch.entries.firstOrNull { it.name == entryName } ?: default
}
